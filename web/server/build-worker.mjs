import {readFile,writeFile} from 'node:fs/promises';
// The three source modules have no runtime dependencies except Node crypto.
// Assemble them deterministically; browser files remain ordinary static ESM.
const core=await readFile(new URL('../dist/core.mjs',import.meta.url),'utf8');
const schema=await readFile(new URL('./schema.mjs',import.meta.url),'utf8');
let worker=await readFile(new URL('./worker.mjs',import.meta.url),'utf8');
for(const statement of ["import {validateData,emptyData} from '../dist/core.mjs';","import {SCHEMA} from './schema.mjs';"]){
 if(!worker.includes(statement))throw new Error('Worker imports changed; update the explicit build inputs.');
 worker=worker.replace(statement,'');
}
const privateExports=source=>source.replace(/^export (?!default)/gm,'');
await writeFile(new URL('../dist/_worker.js',import.meta.url),'// Generated by server/build-worker.mjs; edit the source modules.\n'+privateExports(core)+'\n'+privateExports(schema)+'\n'+privateExports(worker));
console.log('Built the Pages account API worker.');
